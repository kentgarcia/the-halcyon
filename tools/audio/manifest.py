"""manifest.py -- builds audio/manifest.json and audio/REPORT.md from what is actually on disk."""
import json
import os

import numpy as np

import core
import dsp


def measure(path):
    x, sr, ch = core.decode_audio(path, probe=False)
    d = {
        "sr": sr, "ch": ch, "n": len(x), "dur": len(x) / sr if sr else 0.0,
        "peak_db": dsp.peak_db(x), "rms_db": dsp.rms_db(x), "dc": float(np.mean(x)) if len(x) else 0.0,
    }
    d["seam_jump"], d["seam_ratio"] = dsp.seam_stats(x) if len(x) > 2 else (0.0, 0.0)
    d["centroid"] = dsp.spectral_centroid(x) if len(x) > 8 else 0.0
    return d


def _exists(entry, base):
    return os.path.isfile(core.disk_path(entry, base))


def build_manifest(verbose=True):
    sounds = {}
    missing = []
    for e in core.load_catalog():
        bases = core.file_names(e)
        have = [b for b in bases if _exists(e, b)]
        if len(have) != len(bases):
            missing.append(e["name"])
            if not have:
                continue
        durs = []
        for b in have:
            with_stats = measure(core.disk_path(e, b))
            durs.append(with_stats["dur"])
        sounds[e["name"]] = {
            "files": [core.res_path(e, b) for b in have],
            "loop": bool(e["loop"]),
            "bus": e["bus"],
            "db": float(e["db"]),
            "dur": round(max(durs), 3),
            "group": e["group"],
        }
    voice = {}
    for ln in core.load_pa_lines():
        lid = ln["id"]
        ext = core.voice_ext()
        pt = os.path.join(core.DIRS["voice"], f"{lid}_true.{ext}")
        pf = os.path.join(core.DIRS["voice"], f"{lid}_false.{ext}")
        if not os.path.isfile(pt):
            missing.append("voice:" + lid)
            continue
        wants_false = "false" in ln.get("takes", [])
        has_false = wants_false and os.path.isfile(pf)
        if wants_false and not has_false:
            missing.append("voice:" + lid + "_false")
        voice[lid] = {
            "true": f"res://audio/voice/{lid}_true.{ext}",
            "false": f"res://audio/voice/{lid}_false.{ext}" if has_false else None,
            "text": ln["text"],
            "kind": ln["kind"],
            "dur_true": round(measure(pt)["dur"], 3),
            "dur_false": round(measure(pf)["dur"], 3) if has_false else None,
        }
    return {"sounds": sounds, "voice": voice}, missing


def write_manifest(verbose=True):
    man, missing = build_manifest(verbose)
    os.makedirs(core.AUDIO, exist_ok=True)
    with open(core.MANIFEST_PATH, "w", encoding="utf-8") as fh:
        json.dump(man, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    if verbose:
        shown = ", ".join(missing[:8]) + (" ..." if len(missing) > 8 else "")
        print(f"manifest: {len(man['sounds'])} sounds, {len(man['voice'])} voice lines"
              + (f"  ({len(missing)} missing: {shown})" if missing else ""))
    return man, missing


def _fmt_seam(m):
    return f"{m['seam_jump']:.5f} (x{m['seam_ratio']:.2f})"


def write_report(verbose=True):
    cat = {e["name"]: e for e in core.load_catalog()}
    lines = ["# Audio report (generated by tools/audio/generate_all.py -- do not edit by hand)", ""]
    lines += ["All files: mono, 16-bit PCM WAV (or Vorbis where noted), 32000 Hz. Peak/RMS in dBFS; DC = mean sample value.",
              "Seam = |last - first sample| as fraction of full scale, and (xN) that jump divided by the file's own rms "
              "sample-to-sample step (<= ~3 means the wrap point is indistinguishable from any interior sample pair).", ""]
    total_bytes = 0
    for dirkey, title in (("amb", "audio/amb (ambience + dread loops)"), ("music", "audio/music"), ("sfx", "audio/sfx")):
        d = core.DIRS[dirkey]
        files = sorted(f for f in os.listdir(d) if f.endswith(core.AUDIO_EXTS)) if os.path.isdir(d) else []
        lines += [f"## {title}", "", "| file | dur s | peak | RMS | DC | centroid Hz | loop seam |", "|---|---|---|---|---|---|---|"]
        for f in files:
            p = os.path.join(d, f)
            m = measure(p)
            total_bytes += os.path.getsize(p)
            base = os.path.splitext(f)[0]
            nm = base.rsplit("_", 1)[0] if base.rsplit("_", 1)[-1].isdigit() and base.rsplit("_", 1)[0] in cat else base
            is_loop = bool(cat.get(nm, {}).get("loop"))
            lines.append(f"| {f} | {m['dur']:.3f} | {m['peak_db']:.1f} | {m['rms_db']:.1f} | {m['dc']:+.5f} | {m['centroid']:.0f} | "
                         f"{_fmt_seam(m) if is_loop else '-'} |")
        lines.append("")
    # voice
    d = core.DIRS["voice"]
    files = sorted(f for f in os.listdir(d) if f.endswith(core.AUDIO_EXTS)) if os.path.isdir(d) else []
    lines += ["## audio/voice (PA lines; no clicks baked in -- the game plays pa_click_on/off around them)", "",
              "| file | dur s | peak | RMS | DC |", "|---|---|---|---|---|"]
    for f in files:
        p = os.path.join(d, f)
        m = measure(p)
        total_bytes += os.path.getsize(p)
        lines.append(f"| {f} | {m['dur']:.3f} | {m['peak_db']:.1f} | {m['rms_db']:.1f} | {m['dc']:+.5f} |")
    lines.append("")
    lines += [f"Total size of audio/ payload (files above): {total_bytes / 1024 / 1024:.2f} MiB", ""]
    if os.path.isfile(core.NOTES_PATH):
        with open(core.NOTES_PATH, "r", encoding="utf-8") as fh:
            lines += [fh.read().rstrip(), ""]
    with open(core.REPORT_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    if verbose:
        print(f"report: {os.path.relpath(core.REPORT_PATH, core.ROOT)}")
